"""Rows for GFI's fermentation techno-economic model database, one per protein base case.

GFI's Airtable form ('Submit a fermentation TEM to our database!', linked from gfi.org/fermentation-tea)
asks per model: product class, author and year, publication title, citation, DOI/URL (required),
annual production volume (t/yr), reported COP ($/kg), microbe and strain, fermentation modality,
bioreactor type, carbon source, yield (g/g), titer (g/L), productivity and its unit, and the
modelling tool. This script fills those fields from results/analyses.json and the product base cases
(data/pf/products.yaml), so no number is typed. Writes docs/GFI_SUBMISSION.md.

Definitions used:
  COP          cost of production, $/kg target protein (2025 US$): operating cost + straight-line
               depreciation, no return on capital (as SuperPro and most published models report it).
               The model's headline, the minimum selling price with a 14.6%/yr capital charge, is
               given beside it.
  yield        overall glucose to purified target protein, g/g (growth, maintenance and downstream
               losses included): physical.overall_yield_g_g.
  productivity titer / (production batch time + turnaround), g/L/h, the time-averaged volumetric
               productivity of one fermenter.
Run:  .venv/bin/python scripts/gfi_submission.py
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))
from pftea import params  # noqa: E402
from pftea import product as pr  # noqa: E402
from pftea import scenarios as sc  # noqa: E402

R = json.loads((ROOT / "results/analyses.json").read_text())
HOSTS = {"kphaffii": "Komagataella phaffii (Pichia pastoris)", "treesei": "Trichoderma reesei"}
ROUTES = {"concentrate": "UF/DF concentrate", "isolate": "precipitated isolate", "cex": "cation exchange + UF/DF", "acid": "acid (isoelectric) precipitation, as dairy acid casein",
          "aex": "anion exchange + UF/DF"}

rows = []
for prod in sc.PRODUCTS:
    if prod not in R["base"]:
        continue
    p = sc.base_params(prod)
    d = R["base"][prod]
    g = d["design"]
    v = lambda k: params.v(p, k)  # noqa: E731
    methanol = d["physical"].get("methanol_kg", 0) or 0
    carbon = "glucose (dextrose)" + (" + methanol induction" if methanol > 0 else "")
    rows.append(dict(
        protein=pr.load(prod)["name"], volume_t=v("plant.annual_target_protein_t"), cop=d["cop"], msp=d["msp_ccf"],
        host=HOSTS.get(v("strain.host"), v("strain.host")), carbon=carbon,
        yield_=d["physical"]["overall_yield_g_g"], titer=g["titer"],
        productivity=g["titer"] / (g["t_total_h"] + v("fermenter.turnaround_h")),
        route=ROUTES.get(v("plant.spec"), v("plant.spec"))))

common = """| Form field | Value (all rows) |
|---|---|
| Product class | Precision fermentation (secreted food proteins) |
| Author, Year | Moreno Casares, 2026 |
| Publication title | What precision-fermented food proteins cost: an open model (preprint; `report/preprint.pdf`) |
| Citation | Moreno Casares PA (2026). pf-tea, version {version}. https://github.com/PabloAMC/precision-fermentation-tea |
| DOI / URL | **needs the public release** (repository URL, or the Zenodo/engrXiv DOI) |
| Microbe strain | generic producing strain (no named strain; host physiology from published strains) |
| Fermentation modality | aerobic fed-batch (growth phase, then production phase) |
| Bioreactor type | air-sparged stirred tank, {vol:g} m3 (vendor-quote cost curve) |
| Modelling tool / software | Python (open source; Humbird 2021 method: element- and electron-balanced stoichiometry, O2-limited fermenter) |
"""

ver = next(ln.split(":", 1)[1].strip().strip('"') for ln in (ROOT / "CITATION.cff").read_text().splitlines()
           if ln.startswith("version:"))
out = ["# GFI fermentation TEA database: submission draft", "",
       "Generated by `scripts/gfi_submission.py` from `results/analyses.json` "
       f"(results generated {R.get('generated')}); do not edit by hand.", "",
       "GFI's form (gfi.org/fermentation-tea, 'Submit a TEA') takes one model per entry. It requires a DOI or URL, "
       "so you can send it only once the repository or the preprint is public. Send one entry per protein below, "
       "or one entry with this table in the comments field.", "",
       common.format(version=ver, vol=params.v(params.load(), "fermenter.volume_m3")), "",
       "| Protein | Annual volume (t/yr) | Reported COP ($/kg protein) | MSP with capital charge ($/kg) | Microbe | "
       "Carbon source | Yield (g/g, overall) | Titer (g/L) | Productivity (g/L/h) | Downstream |",
       "|---|---|---|---|---|---|---|---|---|---|"]
for r in rows:
    out.append(f"| {r['protein']} | {r['volume_t']:,.0f} | {r['cop']:.2f} | {r['msp']:.2f} | {r['host']} | {r['carbon']} | "
               f"{r['yield_']:.3f} | {r['titer']:.1f} | {r['productivity']:.3f} | {r['route']} |")
out += ["", "Comments field (suggested):", "",
        "> pf-tea is an open cost model for seven precision-fermented food proteins. It uses public data "
        "only, and every input carries a source, a quote and an evidence grade (A-E). It balances elements "
        "and electrons, and it checks oxygen transfer, heat removal and vessel volume, so it never costs a "
        "fermenter that could not run. For each protein it reports a base case at a design-report titer, "
        "the best published titer, the titer in companies' cost models (GFI 2025) and a physical-limit best "
        "case, with tornado and Monte Carlo charts. Before any new claim, it reproduced Humbird's baker's-yeast "
        "workbook and rebuilt NREL 2011, Intelligen 2025 and Voutilainen 2021. COP here is operating cost "
        "plus depreciation in 2025 US$ for a US Midwest plant; the model's headline price adds a 14.6%/yr "
        "capital charge. The author built it with an AI assistant, and AI reviewers audited it; no human "
        "expert has reviewed it yet.", ""]
(ROOT / "docs/GFI_SUBMISSION.md").write_text("\n".join(out))
print("\n".join(out))
